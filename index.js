/**
 * dsh-theme-p3r — Host half.
 *
 * This half deliberately does almost nothing, and that is a finding rather than
 * an oversight: on the current desktop build (@deepseek-ai/dsh-desktop
 * 0.2.1-rc.3) a third-party theme's host entry never activates. The visible
 * symptom is that the sibling theme's `/theme-p5r/media/*` route answers 404 on
 * every port the app listens on, so anything a theme puts behind a custom route
 * is simply never served.
 *
 * Because the background art is the whole point of this skin, it cannot live
 * behind such a route. It is inlined into client.js instead (generated by
 * tools/sync-media.mjs) and handed to the page as the `--p3r-bg` custom
 * property, so the theme has zero host-side dependencies and works whether or
 * not this file is ever composed in.
 *
 * Kept as a valid, side-effect-free cordis plugin so that booting the bundle
 * stays quiet on builds that DO activate host entries.
 */
export const name = 'dsh-theme-p3r'

export function apply(ctx) {
  ctx.logger?.debug?.('dsh-theme-p3r: client-only theme, nothing to mount here')
}
